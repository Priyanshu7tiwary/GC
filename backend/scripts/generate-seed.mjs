// Generates Flyway seed migrations from the frontend's data files so both sides share one source of truth.
// Usage: node backend/scripts/generate-seed.mjs   (run from the repo root)
import { writeFileSync } from 'node:fs';
import { SYLLABUS, ALL_TOPICS } from '../../frontend/src/data/syllabus.js';
import { QUESTIONS } from '../../frontend/src/data/questions.js';
import { MOCKS } from '../../frontend/src/data/mocks.js';

const OUT = new URL('../src/main/resources/db/migration/', import.meta.url);
const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => (v === null || v === undefined ? 'NULL' : `${q(JSON.stringify(v))}::jsonb`);
const HIGH_YIELD = new Set(['Arithmetic', 'Algebra', 'Reading Comprehension', 'Logical Reasoning']);

// ---- topics
const topicRows = ALL_TOPICS.map((t, i) => `(${q(t.id)}, ${q(t.section)}, ${q(t.chapter)}, ${q(t.name)}, ${HIGH_YIELD.has(t.chapter)}, ${i})`);
writeFileSync(new URL('V2__seed_syllabus.sql', OUT),
  `-- Generated by scripts/generate-seed.mjs from frontend/src/data/syllabus.js (${SYLLABUS.length} sections)\n` +
  `INSERT INTO topics (id, section, chapter, name, high_yield, position) VALUES\n${topicRows.join(',\n')};\n`);

// ---- questions (MCQ answers stored as the option index)
const qRows = QUESTIONS.map((x, i) => `(${q(x.id)}, ${q(x.section)}, ${q(x.topic)}, ${q(x.type.toUpperCase())}, ${q(x.q)}, ${q(x.passage)}, ${j(x.options)}, ${q(String(x.answer))}, ${q(x.explanation)}, 'MODERATE', ${i})`);
writeFileSync(new URL('V3__seed_questions.sql', OUT),
  `-- Generated by scripts/generate-seed.mjs from frontend/src/data/questions.js\n` +
  `INSERT INTO questions (id, section, topic, type, prompt, passage, options, answer, explanation, difficulty, position) VALUES\n${qRows.join(',\n')};\n`);

// ---- mock catalogue (previous-year + sectional)
const kind = { pyq: 'PREVIOUS_YEAR', sectional: 'SECTIONAL' };
const mRows = MOCKS.map((m) => `(${q(m.id)}, ${q(kind[m.kind])}, ${q(m.title)}, ${q(m.subtitle)}, ${m.year ?? 'NULL'}, ${m.slot ?? 'NULL'}, ${j(m.sections)}, ${j(m.sectionQs ?? null)}, ${m.sectionMinutes}, ${m.questions}, ${q(m.difficulty)})`);
writeFileSync(new URL('V4__seed_mock_catalogue.sql', OUT),
  `-- Generated by scripts/generate-seed.mjs from frontend/src/data/mocks.js\n` +
  `INSERT INTO mocks (id, kind, title, subtitle, exam_year, slot, sections, section_question_counts, section_minutes, question_count, difficulty) VALUES\n${mRows.join(',\n')};\n`);

console.log(`topics=${topicRows.length} questions=${qRows.length} mocks=${mRows.length}`);
