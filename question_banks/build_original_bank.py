"""Build 99ile's original (non-PYQ) question bank from question_banks/original/*.py.

Source: CAT_2026_Original_Advanced_Question_Bank(1).xlsx, cleaned and verified, plus new questions written for
the app. Every QA and DILR answer is recomputed by its check function; the build stops if any key is wrong.

Outputs:
  question_banks/catalyst_original_bank.json                         the bank, in the admin import format (+ ids)
  backend/src/main/resources/db/migration/V12__original_question_bank.sql   inserts it into `questions`

MCQ options are shuffled with a seed per question id, so answer positions are spread over A–D and stable
between builds. Usage (repository root): python3 question_banks/build_original_bank.py
"""
import collections
import json
import pathlib
import random
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'question_banks' / 'original'))
import dilr  # noqa: E402
import qa  # noqa: E402
import varc  # noqa: E402

OUT_JSON = ROOT / 'question_banks' / 'catalyst_original_bank.json'
OUT_SQL = ROOT / 'backend/src/main/resources/db/migration/V12__original_question_bank.sql'
SOURCE_NOTE = {'xlsx': 'From the CAT 2026 Original Advanced Question Bank (cleaned and verified).',
               'new': 'Written for 99ile.'}


def syllabus():
    text = (ROOT / 'frontend/src/data/syllabus.js').read_text()
    out = {}
    for sec in re.finditer(r"section: '(\w+)',\s*chapters: \[(.*?)\]\s*,\s*\}", text, re.S):
        for ch in re.finditer(r"\{ name: '([^']+)', topics: \[([^\]]*)\]", sec[2]):
            for name in re.findall(r"'([^']+)'", ch[2]):
                out[(sec[1], name)] = (re.sub(r'[^a-z0-9:]+', '-', f'{sec[1]}::{ch[1]}::{name}'.lower()), f'{sec[1]} › {ch[1]} › {name}')
    return out


def shuffle(q):
    if q['type'] != 'MCQ':
        return q
    order = list(range(4))
    random.Random(q['id']).shuffle(order)
    return {**q, 'options': [q['options'][i] for i in order], 'answer': str(order.index(0))}


def collect():
    items = []
    for q in qa.questions():
        items.append({**q, 'id': f"orig-{q['id']}", 'passage': None})
    for s in dilr.sets():
        text = f"{s['title']}\n\n{s['passage']}"
        for i, q in enumerate(s['questions'], 1):
            items.append({**q, 'id': f"orig-dilr-{s['id']}-q{i}", 'section': 'DILR', 'topic': s['topic'], 'passage': text,
                          'difficulty': 'HARD' if i == 3 else 'MODERATE', 'source': 'xlsx'})
    for q in varc.items():
        items.append({**q, 'id': f"orig-{q['id']}", 'source': 'xlsx' if q.get('passage') else 'new'})
    return items


def main():
    topics = syllabus()
    items = [shuffle(q) for q in collect()]
    ids = [q['id'] for q in items]
    assert len(ids) == len(set(ids)), 'duplicate ids'
    rows = []
    for q in items:
        key = (q['section'], q['topic'])
        assert key in topics, f"{q['id']}: {q['topic']!r} is not a {q['section']} syllabus topic"
        assert len(q['id']) <= 40, q['id']
        topic_id, label = topics[key]
        rows.append(dict(id=q['id'], section=q['section'], topic=q['topic'], topicId=topic_id, label=label, type=q['type'],
                         difficulty=q.get('difficulty', 'MODERATE'), passage=q.get('passage'), prompt=q['prompt'],
                         options=q.get('options') or [], answer=q['answer'],
                         explanation=f"{q['explanation']} {SOURCE_NOTE[q.get('source', 'new')]}"))
    OUT_JSON.write_text(json.dumps(rows, ensure_ascii=False, indent=1) + '\n')
    write_sql(rows)

    by = collections.Counter((r['section'], r['type']) for r in rows)
    keys = collections.Counter('ABCD'[int(r['answer'])] for r in rows if r['type'] == 'MCQ')
    print(f'{len(rows)} questions: ' + ', '.join(f'{s} {t} {n}' for (s, t), n in sorted(by.items())))
    print('MCQ answer positions:', dict(sorted(keys.items())))
    print('topics covered:', len({r['topicId'] for r in rows}))


def lit(v):
    return 'NULL' if v is None else "'" + str(v).replace("'", "''") + "'"


def write_sql(rows):
    lines = [
        '-- Generated by question_banks/build_original_bank.py. Do not edit by hand.',
        '-- 99ile’s original (non-PYQ) question bank: the CAT 2026 Original Advanced Question Bank cleaned and',
        '-- verified, plus new questions. Each row is linked to its syllabus topic and labelled.',
        '',
        'INSERT INTO questions (id, section, topic, type, prompt, passage, options, answer, explanation, difficulty, position,',
        '                       origin, created_at, topic_id, topic_label) VALUES',
    ]
    values = []
    for i, r in enumerate(rows, 1):
        opts = "'" + json.dumps(r['options'], ensure_ascii=False).replace("'", "''") + "'::jsonb" if r['type'] == 'MCQ' else 'NULL'
        values.append(f"({lit(r['id'])}, {lit(r['section'])}, {lit(r['topic'])}, {lit(r['type'])}, {lit(r['prompt'])}, {lit(r['passage'])}, "
                      f"{opts}, {lit(r['answer'])}, {lit(r['explanation'])}, {lit(r['difficulty'])}, {10000 + i}, 'BANK', now(), "
                      f"{lit(r['topicId'])}, {lit(r['label'])})")
    lines.append(',\n'.join(values))
    lines.append('ON CONFLICT (id) DO NOTHING;')
    OUT_SQL.write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
